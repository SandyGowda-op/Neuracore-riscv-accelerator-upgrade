/******************************************************************************
 *
 * Module      : metadata_decoder
 *
 * Description :
 *      Decodes NVIDIA-style 2:4 sparsity metadata into
 *      enable masks and non-zero indices.
 *
 * Responsibilities :
 *      - Decode 3-bit metadata
 *      - Generate 4-bit MAC enable mask
 *      - Generate indices of the two non-zero values
 *
 ******************************************************************************/

`timescale 1ns/1ps

module metadata_decoder
(
    //----------------------------------------------------------
    // Input Metadata
    //----------------------------------------------------------

    input logic [2:0] metadata,

    //----------------------------------------------------------
    // Outputs
    //----------------------------------------------------------

    output logic [3:0] enable_mask,

    output logic [1:0] index0,
    output logic [1:0] index1

);

//----------------------------------------------------------
// Metadata Decode Logic
//----------------------------------------------------------

always_comb
begin

    //------------------------------------------------------
    // Defaults
    //------------------------------------------------------

    enable_mask = 4'b0000;

    index0 = 2'd0;
    index1 = 2'd0;

    //------------------------------------------------------
    // Decode Metadata
    //------------------------------------------------------

    case (metadata)

        //--------------------------------------------------
        // Non-zero : (0,1)
        //--------------------------------------------------

        3'b000:
        begin
            enable_mask = 4'b0011;

            index0 = 2'd0;
            index1 = 2'd1;
        end

        //--------------------------------------------------
        // Non-zero : (0,2)
        //--------------------------------------------------

        3'b001:
        begin
            enable_mask = 4'b0101;

            index0 = 2'd0;
            index1 = 2'd2;
        end

        //--------------------------------------------------
        // Non-zero : (0,3)
        //--------------------------------------------------

        3'b010:
        begin
            enable_mask = 4'b1001;

            index0 = 2'd0;
            index1 = 2'd3;
        end

        //--------------------------------------------------
        // Non-zero : (1,2)
        //--------------------------------------------------

        3'b011:
        begin
            enable_mask = 4'b0110;

            index0 = 2'd1;
            index1 = 2'd2;
        end

        //--------------------------------------------------
        // Non-zero : (1,3)
        //--------------------------------------------------

        3'b100:
        begin
            enable_mask = 4'b1010;

            index0 = 2'd1;
            index1 = 2'd3;
        end

        //--------------------------------------------------
        // Non-zero : (2,3)
        //--------------------------------------------------

        3'b101:
        begin
            enable_mask = 4'b1100;

            index0 = 2'd2;
            index1 = 2'd3;
        end

        //--------------------------------------------------
        // Invalid Metadata
        //--------------------------------------------------

        default:
        begin
            enable_mask = 4'b0000;

            index0 = 2'd0;
            index1 = 2'd0;
        end

    endcase

end

endmodule